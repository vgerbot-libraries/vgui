//! Build-time generation of the bundled icon registry.
//!
//! Scans `assets/icons/*.svg` and embeds each file's bytes into a lookup from
//! the icon's file stem to its vector data, so the `icon` component renders
//! the real SVG through gpui's SVG renderer. Adding or removing an `.svg`
//! file is the only change needed to grow or shrink the set.

use std::fs;
use std::path::PathBuf;

fn main() {
    let dir = PathBuf::from("assets/icons");
    println!("cargo:rerun-if-changed=assets/icons");

    let mut names: Vec<String> = Vec::new();
    if let Ok(entries) = fs::read_dir(&dir) {
        for entry in entries.flatten() {
            let path = entry.path();
            if path.extension().and_then(|e| e.to_str()) == Some("svg") {
                if let Some(stem) = path.file_stem().and_then(|s| s.to_str()) {
                    names.push(stem.to_string());
                }
            }
        }
    }
    names.sort();

    let mut out = String::new();
    out.push_str("// @generated by build.rs — do not edit.\n");
    out.push_str("pub fn icon_bytes(name: &str) -> Option<&'static [u8]> {\n");
    out.push_str("    Some(match name {\n");
    for name in &names {
        let bytes = fs::read(dir.join(format!("{name}.svg"))).unwrap();
        out.push_str(&format!(
            "        \"{name}\" => &{:?},\n",
            bytes.as_slice()
        ));
    }
    out.push_str("        _ => return None,\n");
    out.push_str("    })\n");
    out.push_str("}\n\n");
    out.push_str("/// Every bundled icon name, sorted.\n");
    out.push_str("pub static ICON_NAMES: &[&str] = &[\n");
    for name in &names {
        out.push_str(&format!("    \"{name}\",\n"));
    }
    out.push_str("];\n");

    let dest = PathBuf::from(std::env::var("OUT_DIR").unwrap()).join("icon_data.rs");
    fs::write(dest, out).unwrap();
}
